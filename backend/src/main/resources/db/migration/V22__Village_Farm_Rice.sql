-- Village Farm Rice: backend-driven product/pricing configuration, bulk orders and free pickup samples.

CREATE TABLE IF NOT EXISTS rice_products (
    id BIGINT NOT NULL AUTO_INCREMENT,
    code VARCHAR(50) NOT NULL,
    name VARCHAR(120) NOT NULL,
    tagline VARCHAR(255) NULL,
    description TEXT NULL,
    highlights TEXT NULL,
    image_url VARCHAR(500) NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    base_pack_kg INT NOT NULL,
    base_pack_price DECIMAL(12,2) NOT NULL,
    min_order_kg INT NOT NULL,
    order_step_kg INT NOT NULL,
    max_order_kg INT NOT NULL,
    delivery_charge DECIMAL(12,2) NULL,
    payment_note TEXT NULL,
    sample_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sample_weight_grams INT NOT NULL,
    sample_pickup_location TEXT NULL,
    sample_pickup_instructions TEXT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_rice_products_code UNIQUE (code),
    CONSTRAINT chk_rice_products_pack CHECK (base_pack_kg > 0 AND base_pack_price > 0),
    CONSTRAINT chk_rice_products_qty CHECK (min_order_kg > 0 AND order_step_kg > 0 AND max_order_kg >= min_order_kg)
);

CREATE TABLE IF NOT EXISTS rice_orders (
    id BIGINT NOT NULL AUTO_INCREMENT,
    order_number VARCHAR(30) NULL,
    customer_user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    customer_name VARCHAR(120) NOT NULL,
    mobile_number VARCHAR(20) NOT NULL,
    quantity_kg INT NOT NULL,
    base_pack_kg INT NOT NULL,
    base_pack_price DECIMAL(12,2) NOT NULL,
    subtotal DECIMAL(12,2) NOT NULL,
    delivery_charge DECIMAL(12,2) NULL,
    total_amount DECIMAL(12,2) NOT NULL,
    delivery_address TEXT NOT NULL,
    area VARCHAR(100) NOT NULL,
    pincode VARCHAR(10) NOT NULL,
    preferred_delivery_date DATE NULL,
    preferred_delivery_slot VARCHAR(30) NULL,
    delivery_notes TEXT NULL,
    status VARCHAR(30) NOT NULL,
    payment_status VARCHAR(20) NOT NULL,
    admin_notes TEXT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_rice_orders_number UNIQUE (order_number),
    CONSTRAINT uk_rice_orders_idempotency UNIQUE (customer_user_id, idempotency_key),
    CONSTRAINT fk_rice_orders_user FOREIGN KEY (customer_user_id) REFERENCES users(id),
    CONSTRAINT fk_rice_orders_product FOREIGN KEY (product_id) REFERENCES rice_products(id),
    CONSTRAINT chk_rice_orders_qty CHECK (quantity_kg > 0),
    INDEX idx_rice_orders_status (status),
    INDEX idx_rice_orders_payment_status (payment_status),
    INDEX idx_rice_orders_created (created_at)
);

CREATE TABLE IF NOT EXISTS rice_sample_requests (
    id BIGINT NOT NULL AUTO_INCREMENT,
    request_number VARCHAR(30) NULL,
    customer_user_id BIGINT NOT NULL,
    product_id BIGINT NOT NULL,
    customer_name VARCHAR(120) NOT NULL,
    mobile_number VARCHAR(20) NOT NULL,
    sample_weight_grams INT NOT NULL,
    price DECIMAL(12,2) NOT NULL DEFAULT 0.00,
    fulfillment_type VARCHAR(20) NOT NULL DEFAULT 'PICKUP',
    status VARCHAR(30) NOT NULL,
    pickup_location TEXT NULL,
    pickup_time DATETIME NULL,
    pickup_instructions TEXT NULL,
    admin_notes TEXT NULL,
    idempotency_key VARCHAR(64) NOT NULL,
    created_at DATETIME NOT NULL,
    updated_at DATETIME NOT NULL,
    PRIMARY KEY (id),
    CONSTRAINT uk_rice_samples_number UNIQUE (request_number),
    CONSTRAINT uk_rice_samples_idempotency UNIQUE (customer_user_id, idempotency_key),
    CONSTRAINT fk_rice_samples_user FOREIGN KEY (customer_user_id) REFERENCES users(id),
    CONSTRAINT fk_rice_samples_product FOREIGN KEY (product_id) REFERENCES rice_products(id),
    -- Free samples can never carry a charge and are pickup-only (no home delivery).
    CONSTRAINT chk_rice_samples_free CHECK (price = 0),
    CONSTRAINT chk_rice_samples_pickup CHECK (fulfillment_type = 'PICKUP'),
    INDEX idx_rice_samples_status (status),
    INDEX idx_rice_samples_created (created_at)
);

